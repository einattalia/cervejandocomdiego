create or replace function public.mark_order_paid(p_order_id uuid,p_payment_provider text,p_payment_reference text)
returns void language plpgsql security definer set search_path = '' as $$
declare item record; current_status text; current_qty integer;
begin
  select payment_status into current_status from public.orders where id=p_order_id for update;
  if current_status is null then raise exception 'Pedido não encontrado'; end if;
  if current_status='paid' then return; end if;
  for item in select oi.beer_id,oi.quantity,oi.beer_name_snapshot from public.order_items oi where oi.order_id=p_order_id loop
    if item.beer_id is not null then
      select stock_quantity into current_qty from public.beers where id=item.beer_id for update;
      if current_qty is not null and current_qty < item.quantity then
        raise exception 'Estoque insuficiente para concluir baixa de %', item.beer_name_snapshot;
      end if;
      update public.beers
      set stock_quantity=case when stock_quantity is null then null else stock_quantity-item.quantity end,
          stock_status=case when stock_quantity is null then stock_status when stock_quantity-item.quantity=0 then 'sold_out' when stock_quantity-item.quantity<=3 then 'low_stock' else 'in_stock' end
      where id=item.beer_id;
      insert into public.stock_movements(beer_id,order_id,movement_type,quantity,note) values(item.beer_id,p_order_id,'sale',-item.quantity,'Baixa automática após pagamento Stripe');
    end if;
  end loop;
  update public.orders set payment_status='paid',status='paid',payment_provider=p_payment_provider,payment_reference=p_payment_reference,paid_at=now(),updated_at=now() where id=p_order_id;
end;
$$;
revoke all on function public.mark_order_paid(uuid,text,text) from public,anon,authenticated;

