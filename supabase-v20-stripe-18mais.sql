  id uuid primary key default gen_random_uuid(),
  order_code text not null unique,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  delivery_type text not null default 'pickup' check (delivery_type in ('pickup','delivery')),
  delivery_address jsonb,
  notes text,
  subtotal numeric(10,2) not null default 0,
  delivery_fee numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  status text not null default 'awaiting_payment' check (status in ('awaiting_payment','paid','preparing','ready','out_for_delivery','completed','cancelled')),
