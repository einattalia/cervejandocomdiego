create table if not exists public.direct_sales (
  id uuid primary key default gen_random_uuid(),
  sale_date timestamptz not null default now(),
  sale_channel text not null check (sale_channel in ('in_person','whatsapp','event','delivery','other')),
  customer_name text,
  payment_method text not null check (payment_method in ('pix','cash','card','transfer','other')),
  payment_status text not null default 'paid' check (payment_status in ('paid','pending')),
  status text not null default 'completed' check (status in ('completed','cancelled')),
  notes text,
  total numeric(10,2) not null default 0 check (total >= 0),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.direct_sale_items (
  id bigint generated by default as identity primary key,
  direct_sale_id uuid not null references public.direct_sales(id) on delete cascade,
  beer_id uuid references public.beers(id) on delete set null,
  beer_name_snapshot text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_total numeric(10,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

alter table public.direct_sales enable row level security;
alter table public.direct_sale_items enable row level security;

revoke all on public.direct_sales, public.direct_sale_items from anon, authenticated;
grant select on public.direct_sales, public.direct_sale_items to authenticated;
grant usage, select on sequence public.direct_sale_items_id_seq to authenticated;

drop policy if exists "Admins read direct sales" on public.direct_sales;
create policy "Admins read direct sales" on public.direct_sales
  for select to authenticated using (public.is_admin(auth.uid()));
drop policy if exists "Admins read direct sale items" on public.direct_sale_items;
create policy "Admins read direct sale items" on public.direct_sale_items
  for select to authenticated using (public.is_admin(auth.uid()));

alter table public.stock_movements
  add column if not exists direct_sale_id uuid references public.direct_sales(id) on delete set null;
alter table public.stock_movements drop constraint if exists stock_movements_movement_type_check;
alter table public.stock_movements add constraint stock_movements_movement_type_check
  check (movement_type in ('sale','restock','adjustment','refund','direct_sale'));
create index if not exists direct_sales_sale_date_idx on public.direct_sales(sale_date desc);
create index if not exists direct_sale_items_sale_idx on public.direct_sale_items(direct_sale_id);
create index if not exists stock_movements_direct_sale_idx on public.stock_movements(direct_sale_id);

create or replace function public.register_direct_sale(p_sale jsonb, p_items jsonb)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_sale_id uuid;
  v_item jsonb;
  v_beer public.beers%rowtype;
  v_beer_id uuid;
  v_quantity integer;
  v_unit_price numeric(10,2);
  v_line_total numeric(10,2);
  v_total numeric(10,2) := 0;
  v_new_stock integer;
begin
  if auth.uid() is null or not public.is_admin(auth.uid()) then
    raise exception 'Acesso permitido somente a administradores.' using errcode = '42501';
  end if;
  if p_sale is null or p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Informe pelo menos uma cerveja para registrar a venda.' using errcode = '22023';
  end if;

  insert into public.direct_sales(
    sale_date, sale_channel, customer_name, payment_method, payment_status,
    notes, created_by, total
  ) values (
    coalesce((p_sale->>'sale_date')::timestamptz, now()),
    p_sale->>'sale_channel', nullif(trim(p_sale->>'customer_name'), ''),
    p_sale->>'payment_method', coalesce(p_sale->>'payment_status', 'paid'),
    nullif(trim(p_sale->>'notes'), ''), auth.uid(), 0
  ) returning id into v_sale_id;

  for v_item in select value from jsonb_array_elements(p_items) as items(value) loop
    v_beer_id := nullif(v_item->>'beer_id','')::uuid;
    v_quantity := (v_item->>'quantity')::integer;
    v_unit_price := (v_item->>'unit_price')::numeric(10,2);
    if v_beer_id is null or v_quantity is null or v_quantity <= 0 or v_unit_price is null or v_unit_price < 0 then
      raise exception 'Confira a cerveja, a quantidade e o preço de cada item.' using errcode = '22023';
    end if;

    select * into v_beer from public.beers where id = v_beer_id for update;
    if not found then raise exception 'Uma das cervejas selecionadas não foi encontrada.' using errcode = '22023'; end if;
    if v_beer.stock_quantity is not null and v_beer.stock_quantity < v_quantity then
      raise exception 'Estoque insuficiente para %. Disponível: %.', coalesce(v_beer.title,v_beer.name), v_beer.stock_quantity using errcode = '23514';
    end if;

    v_line_total := round(v_unit_price * v_quantity, 2);
    v_total := v_total + v_line_total;
    insert into public.direct_sale_items(direct_sale_id, beer_id, beer_name_snapshot, quantity, unit_price, line_total)
    values(v_sale_id, v_beer_id, coalesce(v_beer.title,v_beer.name), v_quantity, v_unit_price, v_line_total);

    if v_beer.stock_quantity is not null then
      v_new_stock := v_beer.stock_quantity - v_quantity;
      update public.beers set stock_quantity = v_new_stock,
        stock_status = case when v_new_stock = 0 then 'sold_out' when v_new_stock <= 3 then 'low_stock' else 'in_stock' end
        where id = v_beer_id;
    end if;
    insert into public.stock_movements(beer_id, direct_sale_id, movement_type, quantity, note)
    values(v_beer_id, v_sale_id, 'direct_sale', -v_quantity, 'Baixa de estoque por venda direta');
  end loop;

  update public.direct_sales set total = v_total, updated_at = now() where id = v_sale_id;
  return v_sale_id;
end;
$$;

create or replace function public.set_direct_sale_payment(p_sale_id uuid, p_payment_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_admin(auth.uid()) then
    raise exception 'Acesso permitido somente a administradores.' using errcode = '42501';
  end if;
  if p_payment_status is null or p_payment_status not in ('paid','pending') then raise exception 'Status de pagamento inválido.' using errcode = '22023'; end if;
  update public.direct_sales set payment_status = p_payment_status, updated_at = now()
    where id = p_sale_id and status <> 'cancelled';
  if not found then raise exception 'Venda não encontrada ou já cancelada.' using errcode = '22023'; end if;
end;
$$;

create or replace function public.cancel_direct_sale(p_sale_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_sale public.direct_sales%rowtype;
  v_item record;
begin
  if auth.uid() is null or not public.is_admin(auth.uid()) then
    raise exception 'Acesso permitido somente a administradores.' using errcode = '42501';
  end if;
  select * into v_sale from public.direct_sales where id = p_sale_id for update;
  if not found then raise exception 'Venda não encontrada.' using errcode = '22023'; end if;
  if v_sale.status = 'cancelled' then return; end if;

  for v_item in select beer_id, quantity from public.direct_sale_items where direct_sale_id = p_sale_id loop
    if v_item.beer_id is not null then
      update public.beers set stock_quantity = stock_quantity + v_item.quantity,
        stock_status = case when stock_quantity + v_item.quantity = 0 then 'sold_out' when stock_quantity + v_item.quantity <= 3 then 'low_stock' else 'in_stock' end
        where id = v_item.beer_id and stock_quantity is not null;
      insert into public.stock_movements(beer_id, direct_sale_id, movement_type, quantity, note)
      values(v_item.beer_id, p_sale_id, 'restock', v_item.quantity, 'Estoque restaurado após cancelamento de venda direta');
    end if;
  end loop;
  update public.direct_sales set status = 'cancelled', updated_at = now() where id = p_sale_id;
end;
$$;

